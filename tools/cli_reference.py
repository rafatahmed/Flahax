"""Write docs/site/reference/cli.md from the real --help of each command; --check detects drift."""

import argparse
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / 'docs' / 'site' / 'reference' / 'cli.md'
COMMANDS = (
    ('flahax', [], 'The entry point: every command, with examples.'),
    ('flahax mix', ['mix'], 'Five questions to tank A, tank B and the acid, with a batch sheet.'),
    ('flahax batch', ['batch'], 'The same from files in one command, for scripts.'),
)
HEADER = """# Command line

This page shows the help of each command exactly as FlahaX prints it (generated by
`tools/cli_reference.py`). The JSON planning commands `flahax workflow`, `flahax ec` and
`flahax size` read a request on standard input, or ask for it with `--interactive`; see
[Site planning](../developer/site-planning.md).
"""


def help_text(args):
    env = {**os.environ, 'COLUMNS': '100', 'PYTHONIOENCODING': 'utf-8'}
    env['PYTHONPATH'] = str(ROOT / 'src') + os.pathsep + env.get('PYTHONPATH', '')
    result = subprocess.run(
        [sys.executable, '-m', 'flahax', *args, '--help'],
        capture_output=True,
        text=True,
        encoding='utf-8',
        env=env,
        check=True,
    )
    return result.stdout.replace('\r\n', '\n').rstrip()


def page():
    parts = [HEADER]
    for title, args, summary in COMMANDS:
        parts.append(f'## `{title}`\n\n{summary}\n\n```text\n{help_text(args)}\n```\n')
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the page is not current')
    args = parser.parse_args()
    text = page()
    if args.check:
        current = PAGE.read_text(encoding='utf-8') if PAGE.exists() else ''
        if current != text:
            print(f'{PAGE} is not current: run python tools/cli_reference.py')
            return 1
        return 0
    PAGE.write_bytes(text.encode('utf-8'))
    print(f'wrote {PAGE}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
